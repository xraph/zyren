      final index = indices[k];
      if (index == 0) continue;
      final next = x * coAt(index, k + 1) - y * siAt(index, k + 1);
      y = y * coAt(index, k + 1) + x * siAt(index, k + 1);
      x = next;
    }
    return (x, y);
  }

